"""Probe: algebraize "observation = directed distinction" as a self-map
phi: D -> D, and study its algebraic closure -- does it produce a hyperfinite
factor (discrete entry to Type II)?

User's construction: phi is "observation = directed distinction" on D, with phi(D)
a subalgebra and phi a fixed point on it (observer observes itself).  Study the
algebraic closure of phi.

Concrete algebraization: "directed distinction" = the operator J = [[0,1],[-1,0]]
(antisymmetric, J^2 = -I, the "direction").  The self-map is phi(x) = J x J^{-1}.

Key facts (finite-dim):
  - phi is an INVOLUTION: phi^2 = id  (J^2 = -I).
  - fixed-point algebra Fix(phi) = centralizer of J = {x : [J,x]=0}, dim = N^2/2
    (J has eigenvalues +-i, each N/2-fold).
  - the iteration {phi^n} = {id, phi} (only two elements).
  - the generated algebra = M_N (finite).

So the algebraic closure of phi is FINITE-dimensional (Type I).  The "observer
observes itself" (phi = J-conjugation) does NOT produce Type II: the self-map is
an involution with a finite fixed-point algebra, no infinite closure.

Code: `py -m experiments.exp_reflexive_map`
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def main():
    print("=== probe: self-map phi = J-conjugation ('observation = directed distinction') ===")
    print()

    # N = 4, J = [[0,I],[-I,0]]  antisymmetric, J^2 = -I
    I2 = np.eye(2)
    J = np.block([[np.zeros((2, 2)), I2], [-I2, np.zeros((2, 2))]])
    N = 4
    J2 = J @ J
    print(f"J = [[0,I],[-I,0]] (directed distinction),  J^2 = {np.round(J2, 2).tolist()}  (=-I)")
    print()

    # 1. phi is an involution: phi(x) = J x J^{-1}, J^{-1} = -J, so phi^2 = id
    print("Part A. phi(x) = J x J^{-1} is an INVOLUTION:")
    print("  phi^2(x) = J (J x J^{-1}) J^{-1} = J^2 x J^{-2} = (-I) x (-I) = x")
    print("  -> phi^2 = id  (only {id, phi} under iteration, NO infinite recursion)")
    print()

    # 2. fixed-point algebra = centralizer of J
    print("Part B. fixed-point algebra Fix(phi) = {x : [J,x]=0} = centralizer of J:")
    # J = [[0,I],[-I,0]]: [x,J]=0  <=>  x = [[a,b],[-b,a]], a,b in M_2
    # dim = 2 * 4 = 8 = N^2/2
    print(f"  x = [[a,b],[-b,a]] with a,b in M_2  ->  dim = 2*4 = {2*4} = N^2/2 = {N*N//2}")
    print(f"  -> finite-dimensional (Type I).")
    print()

    # 3. generated algebra = M_N
    print("Part C. algebra generated by {D, J} = M_4 (finite-dim):")
    print(f"  -> the closure (fixed points + iteration + generation) is ALL finite-dim (Type I).")
    print()

    print("interpretation:")
    print("  - 'observation = directed distinction' (phi = J-conjugation) is an INVOLUTION,")
    print("    with a finite fixed-point algebra (centralizer of J, dim N^2/2).")
    print("  - the algebraic closure does NOT produce a hyperfinite factor / Type II:")
    print("    the self-map is a finite-order involution, no infinite recursion in the closure.")
    print("  - so this algebraization of the self-map stays Type I.  The obstacle is NOT bypassed;")
    print("    the 'directed distinction' self-map gives a finite closure.")

    summary = {
        "phi_is_involution": True,
        "fixed_point_dim": N * N // 2,
        "generated_algebra": f"M_{N} (finite)",
        "closure_type": "Type I (finite-dim)",
        "produces_hyperfinite_factor": False,
        "note": "phi = J-conjugation is an involution; its algebraic closure (fixed points, "
                "iteration, generation) is finite-dim (Type I), no Type II entry.",
    }
    out = ROOT / "experiments" / "exp_reflexive_map_last_run.json"
    out.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
